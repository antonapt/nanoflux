import argparse
import sys
from importlib.resources import files

import pathtype
from rich_argparse import RichHelpFormatter

from src.tasks import infer, prepare

VERSION = "0.0.1"


def run():
    parser = argparse.ArgumentParser(
        prog="nanoflux",
        epilog=f"Version {VERSION}",
        formatter_class=RichHelpFormatter,
    )
    parser.add_argument("-V", "--version", action="version", version=VERSION)

    # Parent parser for common arguments
    common_parser = argparse.ArgumentParser(add_help=False)
    common_parser.add_argument(
        "-o",
        "--output",
        type=pathtype.Path(writable_or_creatable=True),
        required=True,
        help="Directory to save output files to. To create one upon nonexistence, pass -c/--create-dir",
    )
    common_parser.add_argument(
        "-c",
        "--create-dir",
        action="store_true",
        help="Create output directory and parents",
    )
    common_parser.add_argument(
        "-t",
        "--threads",
        type=int,
        default=4,
        help="Number of threads to use in tool calls and inference",
    )
    common_parser.add_argument(
        "-d", "--debug", action="store_true", help="Enable debug logging"
    )

    subparsers = parser.add_subparsers(
        title="subcommands", dest="command", required=True, metavar="COMMAND"
    )

    prepare_parser = subparsers.add_parser(
        "prepare",
        help="Prepare a SAM/BAM file for nanoflux inference",
        formatter_class=parser.formatter_class,
        parents=[common_parser],
    )

    # required args:
    prepare_parser.add_argument(
        "-i",
        "--input",
        type=pathtype.Path(exists=True, name_matches_re=r"\.[sb]am$", readable=True),
        required=True,
        help="Path to input SAM/BAM file",
    )

    # optional args:
    prepare_parser.add_argument(
        "--ref",
        type=pathtype.Path(exists=True, name_matches_re=r"\.fa$", readable=True),
        required=False,
        default=files("data") / "refs" / "chm13v2.fa",
        help="Path to T2T CHM13v2.0 reference genome",
    )
    prepare_parser.add_argument(
        "--skip-alignment",
        action="store_true",
        help="Skip alignment if SAM/BAM is already aligned to T2T CHM13v2.0",
    )
    prepare_parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Perform a dry-run without actually processing or writing files",
    )
    prepare_parser.add_argument(
        "--read-filter-list",
        type=str,
        default=None,
        help="Path to a list of read names to keep (one read name per line). If not provided, all reads will be kept.",
    )
    prepare_parser.add_argument(
        "--read-filter-feather",
        type=pathtype.Path(exists=True, readable=True),
        default=None,
        help=(
            "Path to a feather file with columns 'read_name', 'nontumor_score_sum', 'covered_cpgs'. "
            "Reads are kept if they do NOT meet both quality thresholds "
            "(i.e., covered_cpgs < --score-filter-min-cpgs OR nontumor_score_sum < --non-tumor-score-threshold). "
            "Requires --non-tumor-score-threshold and --score-filter-min-cpgs."
        ),
    )
    prepare_parser.add_argument(
        "--short-read-min-covered-cpgs",
        type=int,
        default=None,
        help="Minimum number of covered CpGs for a read not to be filtered out. Used with --read-filter-feather.",
    )
    prepare_parser.add_argument(
        "--non-tumor-score-threshold",
        type=float,
        default=None,
        help="Minimum non-tumor score for a read to be considered high-confidence non-tumor. Used with --read-filter-feather.",
    )
    prepare_parser.add_argument(
        "--score-filter-min-cpgs",
        type=int,
        default=None,
        help="Minimum number of covered CpGs for a read to be considered long enough to be assessed for non-tumor status. Used with --read-filter-feather.",
    )
    prepare_parser.add_argument(
        "--feather-cols",
        nargs=3,
        metavar=("READ_NAME_COL", "SCORE_COL", "CPG_COL"),
        default=["read_name", "nontumor_score_sum", "covered_cpgs"],
        help="Column names in the feather file for: read name, score, CpG coverage (default: read_name nontumor_score_sum covered_cpgs). Used with --read-filter-feather.",
    )

    prepare_parser.set_defaults(func=prepare)

    infer_parser = subparsers.add_parser(
        "infer",
        help="Infer from a file generated by nanoflux prepare",
        formatter_class=parser.formatter_class,
        parents=[common_parser],
    )
    infer_parser.add_argument(
        "-i",
        "--input",
        type=pathtype.Path(exists=True, name_matches_re=r"\.bed$", readable=True),
        required=True,
        help="Path to input bed file",
    )

    infer_parser.set_defaults(func=infer)

    args = parser.parse_args(
        args=None if sys.argv[1:] else ["--help"]
    )  # display help if no subcommand is passed
    args.func(args)


if __name__ == "__main__":
    run()
